#!/usr/bin/env bash
# Build Necromancy.sml (dotnet build + MSLM pack).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MSL_DIR="$(cd "$ROOT/../../msl" && pwd)"
OUT_DIR="${OUT_DIR:-$MSL_DIR/Mods}"
MOD_NAME="${MOD_NAME:-Necromancy}"
CONFIG="${CONFIG:-Release}"

# Prefer a user-local or system dotnet install.
if [[ -z "${DOTNET_ROOT:-}" ]]; then
  if [[ -x "${HOME}/.dotnet/dotnet" ]]; then
    export DOTNET_ROOT="${HOME}/.dotnet"
  elif [[ -x /usr/share/dotnet/dotnet ]]; then
    export DOTNET_ROOT=/usr/share/dotnet
  fi
fi
export PATH="${DOTNET_ROOT:-}:${HOME}/.dotnet/tools:${PATH:-}"

if ! command -v dotnet >/dev/null 2>&1; then
  echo "error: dotnet SDK not found (need .NET 6+)." >&2
  exit 1
fi

if ! command -v python3 >/dev/null 2>&1; then
  echo "error: python3 not found." >&2
  exit 1
fi

if [[ ! -f "$MSL_DIR/ModShardLauncher.dll" ]]; then
  echo "error: ModShardLauncher.dll not found in $MSL_DIR" >&2
  exit 1
fi

if [[ ! -f "$ROOT/necromancy.json" ]]; then
  echo "error: necromancy.json missing in $ROOT" >&2
  exit 1
fi

# Embed JSON so the packed DLL works even if EmbeddedResource is stripped.
embed_json() {
  local json="$ROOT/necromancy.json"
  local out="$ROOT/src/NecromancyJsonResource.cs"
  local b64
  b64="$(base64 -w0 "$json" 2>/dev/null || base64 "$json" | tr -d '\n')"
  cat >"$out" <<EOF
namespace Necromancy.Skills;

/// <summary>
/// Auto-generated by build-sml.sh — do not edit by hand.
/// </summary>
internal static class NecromancyJsonResource
{
    const string ContentBase64 = "$b64";

    internal static bool TryOpen(out Stream stream)
    {
        if (string.IsNullOrEmpty(ContentBase64))
        {
            stream = null!;
            return false;
        }

        stream = new MemoryStream(Convert.FromBase64String(ContentBase64));
        return true;
    }

    internal static bool HasContent => !string.IsNullOrEmpty(ContentBase64);
}
EOF
  echo "Embedded necromancy.json into src/NecromancyJsonResource.cs"
}

mkdir -p "$OUT_DIR"
embed_json

echo "Building $MOD_NAME ($CONFIG)..."
dotnet build "$ROOT/Necromancy.csproj" -c "$CONFIG" --nologo

DLL="$ROOT/bin/$CONFIG/net6.0/$MOD_NAME.dll"
if [[ ! -f "$DLL" ]]; then
  echo "error: build output missing: $DLL" >&2
  exit 1
fi

SML="$OUT_DIR/$MOD_NAME.sml"
echo "Packing $SML..."
python3 "$ROOT/pack_sml.py" \
  --root "$ROOT" \
  --dll "$DLL" \
  --out "$SML" \
  --name "$MOD_NAME" \
  --msl "$MSL_DIR"

# Also drop the raw DLL next to Mods for quick inspection / MSL refresh helpers.
cp -f "$DLL" "$OUT_DIR/$MOD_NAME.dll"
echo "Done."
