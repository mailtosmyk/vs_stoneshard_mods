param(
    [Parameter(Mandatory = $true)]
    [string] $Root
)

$jsonPath = Join-Path $Root "src\necromancy.json"
$outPath = Join-Path $Root "src\NecromancyJsonResource.cs"
$versionPath = Join-Path $Root "build.txt"
$versionOutPath = Join-Path $Root "src\NecromancyVersion.cs"

if (-not (Test-Path $jsonPath)) {
    Write-Error "necromancy.json not found: $jsonPath"
    exit 1
}

$ver = "1.0.0"
if (Test-Path $versionPath) {
    $ver = ((Get-Content -Path $versionPath -Raw) -replace "\s", "")
    if ([string]::IsNullOrWhiteSpace($ver)) { $ver = "1.0.0" }
}

$versionCode = @"
namespace Necromancy;

/// <summary>
/// Auto-generated by build-sml — do not edit by hand.
/// Source of truth: build.txt
/// </summary>
internal static class NecromancyVersion
{
    internal const string Value = "$ver";
}
"@
[IO.File]::WriteAllText($versionOutPath, $versionCode)
Write-Host "Embedded build.txt version $ver into src\NecromancyVersion.cs"

$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($jsonPath))
$code = @"
namespace Necromancy.Skills;

/// <summary>
/// Auto-generated by build-sml — do not edit by hand.
/// </summary>
internal static class NecromancyJsonResource
{
    const string ContentBase64 = "$b64";

    internal static bool TryOpen(out Stream stream)
    {
        if (string.IsNullOrEmpty(ContentBase64))
        {
            stream = null!;
            return false;
        }

        stream = new MemoryStream(Convert.FromBase64String(ContentBase64));
        return true;
    }

    internal static bool HasContent => !string.IsNullOrEmpty(ContentBase64);
}
"@

[IO.File]::WriteAllText($outPath, $code)
Write-Host "Embedded necromancy.json into src\NecromancyJsonResource.cs"
